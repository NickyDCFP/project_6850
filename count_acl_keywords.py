all_keywords = keywords["safety"] + keywords["ethics"]

# Function to check if text contains any keyword
def has_keyword(text):
    text_lower = text.lower()
    for kw in all_keywords:
        if kw in text_lower:
            return True
    return False

# Read bib file
with open('/Users/daniroytburg/GitHub/ethics_v_safety/anthology+abstracts.bib', 'r', encoding='utf-8') as f:
    content = f.read()

# Split into entries
entries = re.split(r'@inproceedings\{', content)[1:]  # Skip the first part

count = 0
for entry in entries:
    # Extract year
    year_match = re.search(r'year = "(\d{4})"', entry)
    if year_match:
        year = int(year_match.group(1))
        if 2020 <= year <= 2025:
            # Extract title and abstract
            title_match = re.search(r'title = "([^"]*)"', entry, re.IGNORECASE)
            abstract_match = re.search(r'abstract = "([^"]*)"', entry, re.IGNORECASE)
            if not abstract_match:
                abstract_match = re.search(r'abstract = \{([^}]*)\}', entry, re.IGNORECASE)
            title = title_match.group(1) if title_match else ''
            abstract = abstract_match.group(1) if abstract_match else ''
            text = title + ' ' + abstract
            if has_keyword(text):
                count += 1

print(f'Papers with keywords: {count}')